#include <stdio.h>
#include <arch/zxn.h>

#include "zxn/zxn_frame.h"
#include "zxn/zxn_hw.h"
#include "zxn/zxn_palette.h"
#include "zxn/zxn_tile_map.h"

static const zxn_palette_entry_9_t tile_palette[] = {
    { 0x00, 0x00 },
    { 0xE0, 0x00 },
    { 0x1F, 0x00 },
    { 0xFF, 0x00 },
};

static const zxn_tile_definition_t blank_tile = {{
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
}};

static const zxn_tile_definition_t wall_tile = {{
    0x11, 0x11, 0x11, 0x11,
    0x12, 0x22, 0x22, 0x21,
    0x12, 0x32, 0x23, 0x21,
    0x12, 0x22, 0x22, 0x21,
    0x11, 0x11, 0x11, 0x11,
    0x12, 0x22, 0x22, 0x21,
    0x12, 0x32, 0x23, 0x21,
    0x12, 0x22, 0x22, 0x21,
}};

static const zxn_tile_t wall_tile_entry = {
    .tile_id = 0,
    .tile_attr = 0,
};

static const zxn_tile_t blank_tile_entry = {
    .tile_id = 1,
    .tile_attr = 0,
};

int main(void)
{

    zxn_hw_init();
    zxn_write_palette9( RPC_SELECT_TILEMAP_PALETTE_0, tile_palette, 4);


    zxn_tile_map_init();

    zxnext_tilemap_clear(&wall_tile_entry);
    zxnext_tilemap_set(0, 0, &blank_tile_entry);

    while (1)
    {
        zxn_frame_wait_vblank();
    }

}