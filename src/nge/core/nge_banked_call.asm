; banked_call for nge: preserves the interrupt state.
;
; Based on z88dk's libsrc/target/zxn/far/zxn_banked_call.asm (z88dk is under
; the Clarified Artistic License). Defining banked_call here means the
; linker never pulls in z88dk's version (scripts/check-banks.sh checks this).
;
; The only change: z88dk's version ends with ei, enabling interrupts after
; every banked call. nge keeps interrupts disabled (nge_hw_disable_interrupts)
; so slot 0 can hold RAM instead of the ROM's IM1 handler at $0038. This
; version records whether interrupts were enabled on entry and restores
; exactly that state, both for the called function and on return. The di
; around the stack switch stays, so the routine is also correct once an
; IM2 handler enables interrupts.
;
; Call sequence generated by SDCC for a __banked function:
;     call banked_call
;     defq function        ; address (2 bytes), page (1 byte), unused (1 byte)
;
; Note: on NMOS Z80s, "ld a,i" reads P/V as 0 if an interrupt is accepted
; during it. Irrelevant while interrupts are disabled; see this when adding
; an interrupt handler.

   SECTION code_driver
   PUBLIC banked_call
   EXTERN l_jphl, __IO_NEXTREG_REG
   EXTERN CLIB_BANKING_STACK_SIZE, CLIB_BANKING_SEGMENT

   defc banking_mmu_low = 80 + CLIB_BANKING_SEGMENT * 2
   defc banking_mmu_high = 81 + CLIB_BANKING_SEGMENT * 2


banked_call:
   ld a, i                     ; P/V = IFF2: interrupts enabled on entry
   di
   ; From here to "push af", no instruction changes the flags
   pop hl                      ; hl = the call data after "call banked_call"
   ld (mainsp), sp             ; Save the current stack pointer
   ld sp, (tempsp)             ; Set the stack pointer to the banking stack

   ld a, (cur_bank)            ; Caller's bank in a, interrupt state in f
   push af                     ; Save both on the banking stack

   ld e, (hl)                  ; Fetch the call address in de
   inc hl
   ld d, (hl)
   inc hl
   ld a, (hl)                  ; ...and target page
   inc hl
   inc hl                      ; Skip the unused byte
   push hl                     ; Push the real return address

   ld (tempsp), sp             ; Save the banking stack pointer
   ld sp, (mainsp)             ; and restore the regular stack

   ; Map the new pages (a and a+1); set_mmu changes the flags, so keep them
   ld (cur_bank), a
   push af
   call set_mmu
   pop af

   jp po, call_function        ; Interrupts were disabled: leave them disabled
   ei
call_function:
   ex de, hl                   ; Puts the call address in hl
   call l_jphl                 ; Calls the banked function

   di
   ld (mainsp), sp             ; Switch to the banking stack
   ld sp, (tempsp)

   pop bc                      ; Get the return address
   pop af                      ; Caller's bank in a, entry interrupt state in f

   ld (tempsp), sp             ; Save the banking stack pointer
   ld sp, (mainsp)             ; and restore the regular stack

   push bc                     ; Push the return address

   ; Restore the caller's pages, then its interrupt state
   ld (cur_bank), a
   push af
   call set_mmu
   pop af

   ret po                      ; Interrupts were disabled: return with them disabled
   ei
   ret

set_mmu:
   nextreg banking_mmu_low, a
   inc a
   jr nz, set_mmu_no_rom
   dec a                       ; 0xff corresponds to ROM addresses.
set_mmu_no_rom:
   nextreg banking_mmu_high, a
   ret



   SECTION code_crt_init

   ld a, banking_mmu_low
   ld bc, __IO_NEXTREG_REG
   out (c), a                 ; set next register
   inc b                      ; IO_NEXTREG_DATA
   in a, (c)                  ; read current memory bank
   ld (cur_bank), a           ; saves it in cur_bank

_initbankedsp:
    ;; Classic calls code_crt_init - it's not inlined so we need to preserve
    ;; the return address
IF __CLASSIC
    pop     de
ENDIF
    ld      (tempsp),sp
    ld      hl,-CLIB_BANKING_STACK_SIZE
    add     hl,sp
    ld      sp,hl
IF __CLASSIC
    push    de
ENDIF


   SECTION bss_driver

tempsp:     defw 0
cur_bank:   defb 0
mainsp:     defw 0
