#!/usr/bin/env python3
"""
Writes the starter sprite palette, assets/sprite_palette.gpl, from the
palette bank spec (docs/sprite_import.md section 5.2). From the repository
root:

    python3 -I scripts/sprite_palette.py assets/sprite_palette.gpl

A GIMP palette, which Aseprite loads (Palette, Load Palette): 256 entries,
row b (entries 16b to 16b + 15) is bank b, slot s of each row its entry s.
Run once by hand; the output is committed. It is a start: from then on the
colours in assets/Sprites.aseprite's palette are the source.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import next_colour   # noqa: E402

# Slots 1-8, the same in every colourway: (role, (r, g, b) levels 0-7)
SHARED = [
    ('outline', (0, 0, 1)),
    ('white', (7, 7, 7)),
    ('light grey', (5, 5, 6)),
    ('dark grey', (2, 2, 3)),
    ('red', (6, 1, 1)),
    ('gold', (7, 6, 1)),
    ('brown', (5, 3, 1)),
    ('dark brown', (3, 1, 0)),
]

RAMP_ROLES = ['primary highlight', 'primary light', 'primary mid', 'primary dark',
              'secondary light', 'secondary mid', 'secondary dark']

# The banks: (name, the colours of slots 9-15), or (name, one colour for every slot 1-15)
BANKS = [
    ('player', [(5, 6, 7), (2, 4, 7), (1, 2, 5), (0, 1, 3), (7, 6, 4), (6, 4, 3), (4, 2, 2)]),
    ('flash', (7, 7, 7)),
    ('shadow', (1, 0, 2)),
    ('red', [(7, 5, 4), (7, 2, 2), (5, 0, 1), (3, 0, 1), (7, 6, 4), (6, 4, 2), (4, 2, 1)]),
    ('orange', [(7, 7, 3), (7, 4, 0), (6, 2, 0), (3, 1, 0), (7, 7, 5), (7, 6, 1), (5, 4, 0)]),
    ('gold', [(7, 7, 5), (7, 6, 1), (6, 4, 0), (4, 2, 0), (6, 3, 1), (4, 2, 1), (2, 1, 0)]),
    ('green', [(5, 7, 3), (2, 6, 1), (1, 4, 1), (0, 2, 1), (6, 6, 2), (4, 4, 1), (2, 2, 0)]),
    ('lime', [(6, 7, 2), (4, 7, 0), (2, 5, 0), (1, 3, 1), (6, 4, 6), (4, 1, 4), (2, 0, 2)]),
    ('blue', [(5, 6, 7), (2, 4, 7), (1, 2, 5), (0, 1, 3), (4, 7, 7), (1, 5, 6), (0, 3, 4)]),
    ('ice', [(6, 7, 7), (3, 7, 7), (1, 5, 6), (0, 3, 4), (3, 4, 7), (1, 2, 6), (0, 1, 3)]),
    ('purple', [(6, 5, 7), (5, 2, 6), (3, 1, 4), (1, 0, 2), (7, 4, 6), (6, 2, 4), (3, 0, 2)]),
    ('flesh', [(7, 6, 5), (7, 4, 4), (5, 3, 3), (3, 1, 2), (7, 3, 3), (5, 1, 2), (3, 0, 1)]),
    ('earth', [(6, 5, 3), (5, 3, 1), (3, 2, 1), (2, 1, 0), (7, 6, 4), (5, 4, 3), (3, 2, 2)]),
    ('iron', [(6, 6, 7), (4, 4, 5), (3, 3, 4), (1, 1, 2), (6, 3, 1), (4, 1, 0), (2, 0, 0)]),
    ('bone', [(7, 7, 6), (6, 6, 4), (5, 4, 3), (3, 3, 2), (4, 4, 5), (2, 2, 3), (1, 1, 2)]),
    ('dark', [(3, 2, 4), (2, 1, 3), (1, 0, 2), (0, 0, 1), (7, 2, 2), (5, 0, 1), (3, 0, 0)]),
]


def rgb(levels):
    """8-bit (r, g, b) of 3-bit levels."""
    return tuple(next_colour.LEVELS[v] for v in levels)


def entries():
    """The 256 entries in order: (r, g, b, name)."""
    out = []
    for b, (name, colours) in enumerate(BANKS):
        out.append((0, 0, 0, f'{b} {name}: transparent'))
        if isinstance(colours, tuple):
            out += [rgb(colours) + (f'{b} {name}',) for _ in range(15)]
            continue
        out += [rgb(levels) + (f'{b} {name}: {role}',) for role, levels in SHARED]
        out += [rgb(levels) + (f'{b} {name}: {role}',) for role, levels in zip(RAMP_ROLES, colours)]
    return out


def gpl():
    lines = ['GIMP Palette', 'Name: Jetset sprites', 'Columns: 16',
             '# Generated by scripts/sprite_palette.py: the palette bank spec,',
             '# docs/sprite_import.md section 5.2. Row b is bank b.']
    lines += [f'{r:3d} {g:3d} {b:3d}\t{name}' for r, g, b, name in entries()]
    return '\n'.join(lines) + '\n'


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        print('usage: sprite_palette.py <out.gpl>', file=sys.stderr)
        return 1
    with open(argv[0], 'w') as f:
        f.write(gpl())
    return 0


if __name__ == '__main__':
    sys.exit(main())
