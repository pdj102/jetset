#!/usr/bin/env python3
"""
Imports the map's metatiles from an Aseprite tileset (docs/tileset_import.md).

From the repository root:

    python3 -I scripts/ase2tiles.py assets/Tilesheet.aseprite <out dir> \
        [--names assets/tile_names.txt] [--layer NAME]

Reads the tileset of the file's tilemap layer (the only one, or the one
named): tile n is metatile n, 16 x 16 pixels, tile 0 fully transparent
(rock). Converts the colours to the Next's, gives each metatile a palette
bank (next_colour.fit_banks()), and writes into the out dir:

- tile_defs_data.asm: the tile definitions at $4A00, metatile m as hardware
  tiles 4m to 4m+3, padded to 64 metatiles with transparent ones;
- tile_palette_data.asm: the banks, 16 entries each, in page 133;
- tile_data.h: the palette's page and size, the number of metatiles,
  each metatile's bank (TILE_BANK(m)), and the looks named by the
  tileset's slices (LOOK_<NAME>, LOOK_<NAME>_BANK; tile_names.py);
- tile_rules_data.c: the decorator's tables, made from the names
  (docs/dungeon_decoration.md).

The names file lists the terrains, with their letters for codes, and the
other looks the game uses: with it, names are checked against it (unknown
ones are warnings, ignored; missing ones are errors). On an error it writes nothing, prints every problem found, errors
first, and exits with status 1; warnings are printed and the import goes on.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import aseprite      # noqa: E402
import asm_out       # noqa: E402
import next_colour   # noqa: E402
import tile_names    # noqa: E402

METATILE_PIXELS = 16
HW_TILE_PIXELS = 8
METATILES_MAX = 64
PALETTE_PAGE = 133

DEFS_FILE = 'tile_defs_data.asm'
PALETTE_FILE = 'tile_palette_data.asm'
HEADER_FILE = 'tile_data.h'
RULES_FILE = 'tile_rules_data.c'
RULES_PAGE = 103                 # with the level's data, which the decorator's page maps in


class TileError(Exception):
    """The tileset breaks one of the import's rules."""


def convert(tileset):
    """
    Check the tileset and convert it.

    Returns (banks, assigned, pixels): the banks' colours and each metatile's
    bank (next_colour.fit_banks()), and each metatile's pixel values
    (pixels[m][y][x], 0-15).
    """
    if (tileset.width, tileset.height) != (METATILE_PIXELS, METATILE_PIXELS):
        raise TileError(f'tiles are {tileset.width} x {tileset.height}, '
                        f'not {METATILE_PIXELS} x {METATILE_PIXELS}')
    count = len(tileset.tiles)
    if count == 0:
        raise TileError('the tileset is empty')
    if count > METATILES_MAX:
        raise TileError(f'{count} tiles, at most {METATILES_MAX}')

    graphics = []
    for n, tile in enumerate(tileset.tiles):
        colours = []
        for y, row in enumerate(tile):
            for x, pixel in enumerate(row):
                if pixel[3] == 0:
                    continue
                colour = next_colour.to_next(pixel)
                if colour is None:
                    raise TileError(f'tile {n}, pixel ({x}, {y}): colour {pixel[:3]} '
                                    'is not a Next colour')
                colours.append(colour)
        if n == 0 and colours:
            raise TileError('tile 0 is not fully transparent: it is metatile 0, rock')
        graphics.append(list(dict.fromkeys(colours)))

    banks, assigned = next_colour.fit_banks(graphics)

    pixels = []
    for tile, b in zip(tileset.tiles, assigned):
        pixels.append([[0 if p[3] == 0 else next_colour.pixel_value(banks[b], next_colour.to_next(p))
                        for p in row] for row in tile])
    return banks, assigned, pixels


def hardware_tiles(metatile):
    """A metatile's four 8 x 8 tiles (top left, top right, bottom left, bottom right) as 32 bytes each."""
    tiles = []
    for ty in (0, HW_TILE_PIXELS):
        for tx in (0, HW_TILE_PIXELS):
            data = []
            for y in range(ty, ty + HW_TILE_PIXELS):
                for x in range(tx, tx + HW_TILE_PIXELS, 2):
                    data.append(metatile[y][x] << 4 | metatile[y][x + 1])
            tiles.append(data)
    return tiles


def defs_asm(source, assigned, pixels):
    lines = [
        "; The map's graphics: metatiles of 2 x 2 hardware tiles, 4 bits a pixel",
        '; (map/nge_map.h). Metatile m is hardware tiles 4m to 4m+3: top left, top',
        '; right, bottom left, bottom right. Its number is the map tile ID',
        '; (game/level/level_internal.h, level.h). Pixel values 0 transparent,',
        "; 1-15 through the metatile's palette bank (tile_palette_data.asm).",
        ';',
        f'; Generated by scripts/ase2tiles.py from {source}: do not edit.',
        '',
        'SECTION BANK_5',
        'org 0x4A00',
        '',
        'PUBLIC _tile_pattern',
        '',
        '._tile_pattern',
        '',
        f'sprite_count EQU {METATILES_MAX * 4}',
    ]
    blank = [[0] * METATILE_PIXELS for _ in range(METATILE_PIXELS)]
    for m in range(METATILES_MAX):
        lines.append('')
        if m < len(pixels):
            lines.append(f'; metatile {m}: bank {assigned[m]}')
            metatile = pixels[m]
        else:
            lines.append(f'; metatile {m}: unused (transparent)')
            metatile = blank
        for i, data in enumerate(hardware_tiles(metatile)):
            lines.append(f'sprite{4 * m + i}:')
            lines.append(asm_out.db(data[:16]))
            lines.append(asm_out.db(data[16:]))
    return '\n'.join(lines) + '\n'


def palette_asm(source, banks, assigned):
    lines = [
        '; The tilemap palette for the map: banks of 16 entries, from bank 0 of',
        '; tilemap palette 0, as nge_palette_entry_9_t (RRRGGGBB, then the low blue',
        '; bit). Entry 0 of each bank is transparent. In page 133, assembled for',
        '; slot 7: load it with nge_palette_load9() (hw/nge_palette.h, tile_data.h).',
        ';',
        f'; Generated by scripts/ase2tiles.py from {source}: do not edit.',
        '',
        f'SECTION PAGE_{PALETTE_PAGE}',
        '',
        'PUBLIC _tile_palette',
        '',
        '._tile_palette',
    ]
    for b, bank in enumerate(banks):
        users = ', '.join(str(m) for m, a in enumerate(assigned) if a == b)
        lines.append(f'; bank {b}: metatiles {users}')
        entries = [0] + bank + [0] * (next_colour.BANK_COLOURS - len(bank))
        data = [byte for colour in entries for byte in next_colour.entry_bytes(colour)]
        lines.append(asm_out.db(data[:16]))
        lines.append(asm_out.db(data[16:]))
    return '\n'.join(lines) + '\n'


def _define(name, value, doc=None):
    line = f'#define {name:<32} {value}'
    return f'{line:<42} /**< {doc} */' if doc else line


def looks_lines(looks, names, bases, rules, entries, banks_of):
    """The header's names: every look, every terrain, the tables' sizes and types."""
    lines = [
        '',
        '/*',
        " * Looks, by the names of the tileset's slices (docs/dungeon_decoration.md",
        ' * 5.2): LOOK_<NAME> is its variant 1, LOOK_<NAME>_BANK its bank.',
        ' */',
    ]
    for key in sorted(looks, key=lambda k: looks[k].name):
        look = looks[key]
        tile = look.variants[1][0]
        name = 'LOOK_' + look.name.upper()
        lines.append(_define(name, tile))
        lines.append(_define(name + '_BANK', banks_of[tile]))
    lines += ['', "/* The decorator's tables (tile_rules_data.c): a base a terrain, in TERRAIN_* order */"]
    lines += [_define('TILE_TERRAIN_' + name.upper(), n)
              for n, (_, name) in enumerate(names.terrains if names is not None else [])]
    lines += [
        _define('TILE_TERRAINS', len(bases)),
        _define('TILE_RULES', len(rules)),
        _define('TILE_LOOKS', len(entries)),
        _define('TILE_ANY', f'0x{tile_names.ANY_VALUE:02X}', "A rule's neighbour of any terrain."),
        '',
        '/** A look a rule can choose: a variant, with its share of the picks. */',
        'typedef struct tile_look {',
        '    uint8_t tile_id;',
        '    uint8_t attr;      /**< Its bank, attribute bits 7-4. */',
        '    uint8_t weight;    /**< Its share among its name\'s variants, 1-255. */',
        '} tile_look_t;',
        '',
        "/** A rule: a look with a code, on the 8 neighbours' terrains. */",
        'typedef struct tile_rule {',
        '    uint8_t want[8];   /**< N, NE, E, SE, S, SW, W, NW: a terrain, or TILE_ANY. */',
        '    uint8_t first;     /**< Its variants: tile_looks[first] on. */',
        '    uint8_t count;',
        '} tile_rule_t;',
        '',
        "/** A terrain's base: its rules in the order tried, its default (all TILE_ANY) last. */",
        'typedef struct tile_base {',
        '    uint8_t first;     /**< tile_rules[first] on. */',
        '    uint8_t count;',
        '} tile_base_t;',
        '',
        'extern const tile_look_t tile_looks[];',
        'extern const tile_rule_t tile_rules[];',
        'extern const tile_base_t tile_bases[];',
    ]
    return lines


def rules_c(source, bases, rules, entries):
    """tile_rules_data.c: the tables, constants in the level's data page."""
    def body(items):
        return items if items else ['    { 0 },   /* none: C has no empty arrays */']

    def want_text(want):
        return ', '.join('TILE_ANY' if w == tile_names.ANY_VALUE else str(w) for w in want)

    lines = [
        '/*',
        " * The decorator's tables, made from the tileset's look names",
        ' * (docs/dungeon_decoration.md 5.4): constants in page 103, with the',
        " * level's data, mapped in slot 7 while the level's code in page 102 runs.",
        ' *',
        f' * Generated by scripts/ase2tiles.py from {source}: do not edit.',
        ' */',
        '#ifdef __SDCC',
        f'#pragma constseg PAGE_{RULES_PAGE}',
        '#endif',
        '',
        '#include "data/tile_data.h"',
        '',
        f'const tile_look_t tile_looks[{max(1, len(entries))}] = {{',
    ]
    lines += body([f'    {{ {tile}, 0x{bank << 4:02X}, {weight} }},   /* {name} */'
                   for tile, bank, weight, name in entries])
    lines += ['};', '', f'const tile_rule_t tile_rules[{max(1, len(rules))}] = {{']
    lines += body([f'    {{ {{ {want_text(want)} }}, {first}, {count} }},   /* {name} */'
                   for want, first, count, name in rules])
    lines += ['};', '', f'const tile_base_t tile_bases[{max(1, len(bases))}] = {{']
    lines += body([f'    {{ {first}, {count} }},   /* {terrain} */' for terrain, first, count in bases])
    lines.append('};')
    return '\n'.join(lines) + '\n'


def header(source, banks, assigned, names_lines=()):
    lines = [
        '#ifndef TILE_DATA_H',
        '#define TILE_DATA_H',
        '',
        '/**',
        ' * @file tile_data.h',
        " * @brief The map's metatiles (tile_defs_data.asm) and their palette",
        ' *        (tile_palette_data.asm).',
        ' *',
        f' * Generated by scripts/ase2tiles.py from {source}: do not edit.',
        ' *',
        " * Each metatile is drawn through one palette bank: a map tile's attribute",
        ' * is TILE_BANK(m) << 4. TILE_BANK() takes a metatile number that is a',
        ' * constant (a literal, or a macro naming one).',
        ' */',
        '',
        '#include <stdint.h>',
        '',
        '#include "hw/nge_palette.h"',
        '',
        f'#define TILE_PALETTE_PAGE   {PALETTE_PAGE:<4} /**< SECTION PAGE_{PALETTE_PAGE} in tile_palette_data.asm. */',
        f'#define TILE_PALETTE_BANKS  {len(banks):<4} /**< Banks in tile_palette, 16 entries each. */',
        f'#define TILE_PALETTE_ENTRIES {len(banks) * next_colour.BANK_SIZE:<3} /**< Entries in tile_palette: load them from index 0. */',
        f'#define TILE_METATILES      {len(assigned):<4} /**< Metatiles in the tileset, tile 0 included. */',
        '',
    ]
    lines += [f'#define TILE_BANK_{m}  {b}' for m, b in enumerate(assigned)]
    lines += [
        '',
        "/** A metatile's bank, from a metatile number that is a constant. */",
        '#define TILE_BANK(m)    TILE_BANK_X(m)',
        '#define TILE_BANK_X(m)  TILE_BANK_##m',
    ]
    lines += list(names_lines)
    lines += [
        '',
        'extern const nge_palette_entry_9_t tile_palette[];',
        '',
        '#endif',
    ]
    return '\n'.join(lines) + '\n'


def run(source, out_dir, layer=None, names=None):
    """
    Import source into out_dir. names: the names file (tile_names.Names),
    or None (every base accepted, none required, no terrains). Returns (summary lines,
    warnings). Raises TileError with every problem on an error, writing
    nothing.
    """
    sprite = aseprite.read(source)
    tileset = sprite.tilemap_tileset(layer)
    banks, assigned, pixels = convert(tileset)
    looks, problems = tile_names.collect(sprite, names, layer)
    errors = [p for p in problems if p.error]
    warnings = [p for p in problems if not p.error]
    if errors:
        raise TileError('\n'.join(str(p) for p in errors + warnings))
    try:
        bases, rules, entries = tile_names.tables(looks, names, assigned)
    except ValueError as e:
        raise TileError(str(e)) from e
    asm_out.write_all(out_dir, {
        DEFS_FILE: defs_asm(source, assigned, pixels),
        PALETTE_FILE: palette_asm(source, banks, assigned),
        HEADER_FILE: header(source, banks, assigned, looks_lines(looks, names, bases, rules, entries, assigned)),
        RULES_FILE: rules_c(source, bases, rules, entries),
    })
    summary = [f'{source}: {len(assigned)} metatiles, {len(banks)} of {next_colour.BANKS_MAX} banks, '
               f'{len(looks)} names, {len(rules)} rules']
    for b, bank in enumerate(banks):
        users = ', '.join(str(m) for m, a in enumerate(assigned) if a == b)
        summary.append(f'  bank {b}: {len(bank)} colours, metatiles {users}')
    named = {tile for look in looks.values() for tile, _, _ in look.ordered()}
    unnamed = [str(m) for m in range(1, len(assigned)) if m not in named]
    if looks and unnamed:
        summary.append(f'  tiles with no name: {", ".join(unnamed)}')
    return summary, warnings


def main(argv=None):
    parser = argparse.ArgumentParser(description="Import the map's metatiles from an Aseprite tileset.")
    parser.add_argument('source', help='the .aseprite file')
    parser.add_argument('out_dir', help='where to write the generated files')
    parser.add_argument('--layer', help='the tilemap layer, if the file has several')
    parser.add_argument('--names', help="the game's names (assets/tile_names.txt)")
    args = parser.parse_args(argv)
    try:
        names = tile_names.read_names(args.names) if args.names else None
        summary, warnings = run(args.source, args.out_dir, args.layer, names)
    except TileError as e:
        for line in str(e).splitlines():
            print(f'ase2tiles: {line if line.startswith(("error:", "warning:")) else "error: " + line}',
                  file=sys.stderr)
        return 1
    except (OSError, aseprite.AsepriteError, next_colour.ColourError, tile_names.NamesFileError) as e:
        print(f'ase2tiles: error: {e}', file=sys.stderr)
        return 1
    for warning in warnings:
        print(f'ase2tiles: {warning}', file=sys.stderr)
    print('\n'.join(summary))
    return 0


if __name__ == '__main__':
    sys.exit(main())
